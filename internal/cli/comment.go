package cli

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/GerMP21/Omnisnap/internal/schema"
)

// GitHub's comment limit is 65,536 characters; leave room for the truncation
// note and link.
const commentLimit = 65000

// commentMarker identifies Omnisnap's comment, so the Action updates it in
// place instead of posting a second one.
const commentMarker = "<!-- omnisnap-report -->"

// runComment is `omnisnap comment <merged-bundle>` (Task 80): render the one
// PR comment from a merged summary.
func runComment(args []string) int {
	fs := flag.NewFlagSet("comment", flag.ContinueOnError)
	reportURL := fs.String("report-url", "", "link to the merged report artifact")
	runURL := fs.String("run-url", "", "link to the workflow run")
	limit := fs.Int("limit", commentLimit, "markdown length limit")
	if err := fs.Parse(args); err != nil {
		fmt.Fprintln(os.Stderr, "omnisnap:", err)
		return ExitUsage
	}
	pos := fs.Args()
	if len(pos) != 1 {
		fmt.Fprintln(os.Stderr, "omnisnap: comment takes one merged bundle directory")
		return ExitUsage
	}
	b, err := os.ReadFile(filepath.Join(pos[0], "summary.json"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "omnisnap: comment:", err)
		return ExitUsage
	}
	var s schema.Summary
	if err := json.Unmarshal(b, &s); err != nil {
		fmt.Fprintln(os.Stderr, "omnisnap: comment: summary.json:", err)
		return ExitInternal
	}
	fmt.Print(RenderComment(s, CommentLinks{Report: *reportURL, Run: *runURL, Limit: *limit}))
	return ExitOK
}

// CommentLinks are the URLs the comment points at.
type CommentLinks struct {
	Report string
	Run    string
	Limit  int
}

// RenderComment renders the merged summary as one markdown comment.
func RenderComment(s schema.Summary, l CommentLinks) string {
	limit := l.Limit
	if limit <= 0 {
		limit = commentLimit
	}
	var b strings.Builder
	b.WriteString(commentMarker + "\n")
	b.WriteString("## Omnisnap: cross-engine layout\n\n")
	fmt.Fprintf(&b, "%d comparison(s) on %d page(s)", len(s.Results), len(s.Pages))
	if len(s.Hosts) > 0 {
		var hosts []string
		for _, h := range s.Hosts {
			hosts = append(hosts, h.ID)
		}
		sort.Strings(hosts)
		b.WriteString(" · hosts: " + strings.Join(hosts, ", "))
	}
	b.WriteString("\n\n")

	// Results grouped by page.
	byPage := map[string][]schema.Result{}
	var order []string
	pageURL := map[string]string{}
	for _, r := range s.Results {
		key := r.Page.Slug
		if _, ok := byPage[key]; !ok {
			order = append(order, key)
			pageURL[key] = r.Page.URL
		}
		byPage[key] = append(byPage[key], r)
	}
	sort.Strings(order)

	if len(s.Results) == 0 {
		b.WriteString("No comparisons: every engine capture failed or no engine was available.\n\n")
	}
	for _, slug := range order {
		results := byPage[slug]
		fmt.Fprintf(&b, "### %s\n\n", slug)
		if u := pageURL[slug]; u != "" {
			fmt.Fprintf(&b, "<%s>\n\n", u)
		}
		sort.SliceStable(results, func(i, j int) bool {
			if results[i].Host.ID != results[j].Host.ID {
				return results[i].Host.ID < results[j].Host.ID
			}
			return results[i].Engine.Engine < results[j].Engine.Engine
		})
		for _, r := range results {
			head := fmt.Sprintf("- **%s** on %s vs %s: %s · %d report, %d info",
				r.Engine.Engine, hostName(r), r.Baseline.Engine, r.Status, r.Stats.Report, r.Stats.Info)
			b.WriteString(head + "\n")
			reported := reportCauses(r.Causes)
			for i, c := range reported {
				if i >= 3 {
					fmt.Fprintf(&b, "  - … %d more report cause(s)\n", len(reported)-3)
					break
				}
				fmt.Fprintf(&b, "  - %s — `%s` (%s)\n", c.Title, c.Selector, strings.Join(c.Kinds, ", "))
			}
		}
		b.WriteString("\n")
	}

	// Notes: skipped engines, unreachable pages, warnings worth surfacing.
	var notes []string
	for _, sk := range s.Skipped {
		notes = append(notes, fmt.Sprintf("%s: %s skipped: %s", hostOrAny(sk.Host), sk.Engine, sk.Reason))
	}
	for _, r := range s.Results {
		if r.Status == schema.StatusUnreachable || r.Status == schema.StatusFailed {
			notes = append(notes, fmt.Sprintf("%s/%s: %s", hostName(r), r.Page.Slug, r.Status))
		}
	}
	if len(notes) > 0 {
		b.WriteString("### Notes\n\n")
		for _, n := range notes {
			b.WriteString("- " + n + "\n")
		}
		b.WriteString("\n")
	}
	var links []string
	if l.Report != "" {
		links = append(links, "[merged report]("+l.Report+")")
	}
	if l.Run != "" {
		links = append(links, "[workflow run]("+l.Run+")")
	}
	if len(links) > 0 {
		b.WriteString(strings.Join(links, " · ") + "\n\n")
	}
	b.WriteString("<sub>Report only: Omnisnap never fails a build. Generated by omnisnap " + s.Tool.Version + ".</sub>\n")

	out := b.String()
	if len(out) > limit {
		// GitHub caps comments at 65,536 characters: truncate at a line
		// boundary and point at the report.
		cut := out[:limit]
		if i := strings.LastIndexByte(cut, '\n'); i > 0 {
			cut = cut[:i]
		}
		out = cut + "\n\n… comment truncated; see the merged report" + linkSuffix(l.Report) + " for every cause.\n"
	}
	return out
}

// reportCauses returns the Report-tier causes, strongest first (the summary is
// already ranked).
func reportCauses(causes []schema.Cause) []schema.Cause {
	var out []schema.Cause
	for _, c := range causes {
		if c.Tier == schema.TierReport {
			out = append(out, c)
		}
	}
	return out
}

func hostName(r schema.Result) string {
	if r.Host.ID != "" {
		return r.Host.ID
	}
	return r.Host.OS + "/" + r.Host.Arch
}

func hostOrAny(h string) string {
	if h == "" {
		return "any host"
	}
	return h
}

func linkSuffix(url string) string {
	if url == "" {
		return ""
	}
	return " (" + url + ")"
}
